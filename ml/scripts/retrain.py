"""Offline retraining: a challenger built with the labels of the replayed days.

Training data = original train + validation periods + replayed week 1 (from the database
export); week 2 is a gap; week 3 calibrates (isotonic) and sets the cost-optimal expected-loss
threshold under the daily capacity; week 4 compares champion and challenger on the same rows
(never used for fitting), overall and excluding customers who had a fraud in the challenger's
training data. Same 59 features, same encoder, same LightGBM recipe as the champion.

Steps (repo root):
    docker compose exec -T backend python -m app.scripts.export_training_data \
        --from 2018-04-28 --to 2018-05-26 > data/processed/replayed_labelled.parquet
    ml/.venv/Scripts/python ml/scripts/retrain.py
    docker compose exec backend python -m app.scripts.register_model <new version> \
        --anomaly iforest-2026.10.27-1

Writes artifacts/models/lgbm-<date>-<n>/ (metadata with the comparison),
artifacts/monitoring/drift_reference-<version>.json and reports/retrain_comparison.md.
"""

from __future__ import annotations

import argparse
import json
import time

import numpy as np
import pandas as pd

from fraudml import config
from fraudml.evaluate import CostConfig
from fraudml.evaluate.threshold import optimise_threshold
from fraudml.features.keys import make_uid
from fraudml.features.pipeline import CATEGORICAL_FEATURES, FEATURES_CURATED
from fraudml.models import data as model_data
from fraudml.models.calibration import IsotonicCalibrator, expected_loss
from fraudml.models.lgbm import LGBM_DEFAULTS, make_lgbm
from fraudml.models.retrain import (
    WINDOWS,
    align_features,
    fraud_customers,
    paired_bootstrap_pr_auc,
    split_windows,
    window_metrics,
)
from fraudml.monitoring.drift import build_reference
from fraudml.registry import load_model, save_model

SEED = 42
CHAMPION = "lgbm-2026.10.27-1"
EXPORT = config.PROCESSED_DIR / "replayed_labelled.parquet"
REPORT = config.REPORTS_DIR / "retrain_comparison.md"
# Champion's numbers on the comparison week, from the replay's monitoring (= offline test week 4).
EXPECTED_CHAMPION_WEEK4 = {"n": 19941, "alerts_per_day": 149.285714, "precision": 0.257416}


def customer_keys() -> pd.Series:
    """TransactionID -> pseudo customer key for every labelled row (same function as the DB)."""
    cols = [config.ID_COL, config.TIME_COL, "card1", "addr1", "D1"]
    raw = pd.read_parquet(config.PROCESSED_DIR / "train.parquet", columns=cols)
    return pd.Series(make_uid(raw).to_numpy(), index=raw[config.ID_COL].to_numpy())


def days_of(times: pd.Series) -> np.ndarray:
    return pd.to_datetime(times).dt.normalize().to_numpy()


def fmt(v, kind: str) -> str:
    if v is None:
        return "—"
    formats = {"pct": f"{v:.1%}", "num": f"{v:.3f}", "dec1": f"{v:.1f}", "usd": f"${v:,.0f}"}
    return formats[kind]


def report(comparison: dict, meta: dict) -> str:
    rows = [
        ("PR-AUC", "pr_auc", "num"),
        ("Precision of alerts", "precision", "pct"),
        ("Recall", "recall", "pct"),
        ("Fraud $ caught", "fraud_value_caught", "pct"),
        ("Net savings", "net_savings", "usd"),
        ("Alerts per day", "alerts_per_day", "dec1"),
    ]
    b = comparison["pr_auc_diff_bootstrap"]
    lines = [
        f"# Retraining: champion vs challenger ({meta['version']})",
        "",
        "Generated by `ml/scripts/retrain.py`. Comparison week "
        f"{' → '.join(WINDOWS['comparison'])} (excluded end), never used for fitting.",
        "",
        f"- Challenger training: {meta['training_rows']:,} rows "
        f"(train + validation + replayed {' → '.join(WINDOWS['train_extra'])}); "
        f"calibration + threshold on {' → '.join(WINDOWS['calibration'])}; "
        f"gap {' → '.join(WINDOWS['gap'])}.",
        f"- Thresholds (expected loss, USD): champion {comparison['champion_threshold']:.2f} · "
        f"challenger {comparison['challenger_threshold']:.2f}.",
        f"- PR-AUC difference (challenger − champion): {b['diff']:+.4f}, day-block bootstrap "
        f"95% interval [{b['low']:+.4f}, {b['high']:+.4f}] over only {b['days']} days "
        f"({b['share_positive']:.0%} of resamples favour the challenger).",
        "",
    ]
    scopes = {
        "overall": "All customers",
        "excl_fraud_customers": "Excluding customers with a fraud in the challenger's training",
    }
    for scope, title in scopes.items():
        ch, cl = comparison["champion"][scope], comparison["challenger"][scope]
        lines += [
            f"## {title} ({ch['n']:,} transactions, {ch['n_fraud']:,} frauds)",
            "",
            "| Metric | Champion | Challenger |",
            "|---|---:|---:|",
        ]
        lines += [
            f"| {label} | {fmt(ch[k], kind)} | {fmt(cl[k], kind)} |" for label, k, kind in rows
        ]
        lines.append("")
    return "\n".join(lines)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--dry-run", action="store_true", help="train and compare, save nothing")
    args = parser.parse_args()
    if not EXPORT.exists():
        raise SystemExit(f"missing {EXPORT}: run export_training_data first (see the docstring)")

    t0 = time.perf_counter()
    cfg = CostConfig()
    features = list(FEATURES_CURATED)
    train = model_data.load_period("train")
    val = model_data.load_period("validation")
    template = train.X

    replayed = pd.read_parquet(EXPORT)
    parts = split_windows(replayed)
    sources = replayed["label_source"].value_counts().to_dict()
    print(f"export: {len(replayed):,} rows · label sources {sources}")
    for name, part in parts.items():
        rate = part["label"].astype(float).mean() if len(part) else float("nan")
        print(
            f"  {name:<12} {' → '.join(WINDOWS[name])}: {len(part):,} labelled rows, "
            f"fraud {rate:.2%}"
        )

    w1, w3, w4 = parts["train_extra"], parts["calibration"], parts["comparison"]
    X_train = pd.concat([train.X, val.X, align_features(w1, template)], ignore_index=True)[features]
    y_train = pd.concat([train.y, val.y, w1["label"].astype("int8")], ignore_index=True).to_numpy()
    keys = customer_keys()
    uid_train = pd.Series(
        np.concatenate(
            [
                train.meta["TransactionID"].map(keys).to_numpy(dtype=object),
                val.meta["TransactionID"].map(keys).to_numpy(dtype=object),
                w1["customer_key"].to_numpy(dtype=object),
            ]
        )
    )
    seen_fraud = fraud_customers(uid_train, y_train)
    print(f"training rows {len(X_train):,} · fraud rate {y_train.mean():.2%} · "
          f"customers with a fraud {len(seen_fraud):,}")  # fmt: skip

    # ---------------- fit, calibrate, threshold ----------------
    model = make_lgbm(seed=SEED).fit(X_train, y_train)
    X3 = align_features(w3, template)[features]
    y3 = w3["label"].astype("int8").to_numpy()
    raw3 = model.predict_proba(X3)[:, 1]
    cal = IsotonicCalibrator().fit(raw3, y3)
    p3 = cal.predict(raw3)
    el3 = expected_loss(p3, w3["amount"].to_numpy())
    thr = optimise_threshold(y3, el3, w3["amount"].to_numpy(), days_of(w3["transaction_time"]), cfg)
    print(f"calibration week: threshold ${thr.threshold:.2f} · {thr.alerts_per_day:.1f} alerts/day")

    # ---------------- comparison week ----------------
    X4 = align_features(w4, template)[features]
    y4 = w4["label"].astype("int8").to_numpy()
    amount4 = w4["amount"].to_numpy()
    day4 = days_of(w4["transaction_time"])
    p4 = cal.predict(model.predict_proba(X4)[:, 1])
    challenger_alert = expected_loss(p4, amount4) >= thr.threshold
    champion_meta = load_model(CHAMPION).metadata
    keep = ~w4["customer_key"].astype(str).isin(seen_fraud).to_numpy()

    def side(prob, alert) -> dict:
        return {
            "overall": window_metrics(y4, prob, amount4, alert, day4, cfg),
            "excl_fraud_customers": window_metrics(
                y4[keep], prob[keep], amount4[keep], alert[keep], day4[keep], cfg
            ),
        }

    champion = side(w4["champion_score"].to_numpy(), w4["champion_alert"].to_numpy().astype(bool))
    challenger = side(p4, challenger_alert)
    boot = paired_bootstrap_pr_auc(y4, w4["champion_score"].to_numpy(), p4, day4)
    comparison = {
        "window": WINDOWS["comparison"],
        "pr_auc_diff_bootstrap": boot,
        "champion_version": CHAMPION,
        "champion_threshold": float(champion_meta["threshold"]),
        "challenger_threshold": thr.threshold,
        "champion": champion,
        "challenger": challenger,
    }

    # The champion side must reproduce its monitored week (same stored predictions).
    o = champion["overall"]
    for k, v in EXPECTED_CHAMPION_WEEK4.items():
        assert abs(o[k] - v) < 1e-5, f"champion {k} {o[k]} != monitoring {v}"
    print("champion week-4 numbers = monitoring / offline test week 4: OK")
    for name, s in (("champion", champion), ("challenger", challenger)):
        a, e = s["overall"], s["excl_fraud_customers"]
        print(
            f"{name:<10} PR-AUC {a['pr_auc']:.4f} (excl {e['pr_auc']:.4f}) · precision "
            f"{a['precision']:.3f} · recall {a['recall']:.3f} · "
            f"fraud $ {a['fraud_value_caught']:.1%}"
            f" · savings ${a['net_savings']:,.0f} (excl ${e['net_savings']:,.0f}) · "
            f"{a['alerts_per_day']:.1f} alerts/day"
        )

    print(
        f"PR-AUC difference (challenger - champion) {boot['diff']:+.4f}, day-block bootstrap 95% "
        f"[{boot['low']:+.4f}, {boot['high']:+.4f}] over {boot['days']} days, "
        f"{boot['share_positive']:.0%} of resamples > 0"
    )

    if args.dry_run:
        print(f"dry run: nothing saved ({time.perf_counter() - t0:.0f} s)")
        return

    # ---------------- artifact, drift reference, report ----------------
    cal_metrics = window_metrics(y3, p3, w3["amount"].to_numpy(), el3 >= thr.threshold,
                                 days_of(w3["transaction_time"]), cfg)  # fmt: skip
    folder = save_model(
        model,
        cal,
        {
            "features": features,
            "categorical_features": [c for c in features if c in CATEGORICAL_FEATURES],
            "params": {**LGBM_DEFAULTS, "random_state": SEED},
            "policy": "expected_loss",
            "threshold": thr.threshold,
            "cost_config": cfg.to_dict(),
            "training_data_window": [config.SPLIT_DATES["train"][0], WINDOWS["train_extra"][1]],
            "calibration_window": list(WINDOWS["calibration"]),
            "validation_metrics": {"overall": cal_metrics, "window": "calibration week"},
            "comparison": comparison,
            "training_rows": int(len(X_train)),
            "notes": "Retrained with replayed labels (train + validation + replayed week 1); "
            "gap week 2; calibrated on week 3; compared with the champion on week 4.",
        },
    )
    loaded = load_model(folder.name, folder.parent)
    same = np.array_equal(loaded.predict_proba(X4), p4)
    assert same, "artifact round trip changed the scores"
    print(f"saved {folder.relative_to(config.REPO_ROOT)} · round trip identical")

    ref = build_reference(X_train, set(CATEGORICAL_FEATURES), p3, meta={"model": folder.name})
    ref_path = config.ARTIFACTS_DIR / "monitoring" / f"drift_reference-{folder.name}.json"
    ref_path.parent.mkdir(parents=True, exist_ok=True)
    ref_path.write_text(json.dumps(ref), encoding="utf-8")

    meta = {"version": folder.name, "training_rows": len(X_train)}
    REPORT.write_text(report(comparison, meta), encoding="utf-8")
    print(
        f"wrote {ref_path.relative_to(config.REPO_ROOT)} and {REPORT.relative_to(config.REPO_ROOT)}"
    )
    print(f"done in {time.perf_counter() - t0:.0f} s · next: register_model {folder.name} "
          f"--anomaly iforest-2026.10.27-1")  # fmt: skip


if __name__ == "__main__":
    main()
